        if (request.method() !== "GET") writes.push({ path: url.pathname, payload });
        if (url.pathname === "/fixture/user") return reply(user);
        if (url.pathname === "/fixture/priorities") { priorities = payload; return reply(priorities); }
        if (url.pathname.endsWith("/app-preferences")) return reply({ antiInflammatorySupport: false });
