        if (url.origin !== origin) { unexpected.push(request.url()); return route.abort(); }
        if (request.isNavigationRequest()) return route.fulfill({ contentType: "text/html", body: `<html lang="${language}"><head><meta name="viewport" content="width=device-width,initial-scale=1"><style>${css}</style></head><body style="margin:0;background:black"><div id="root"></div></body></html>` });
