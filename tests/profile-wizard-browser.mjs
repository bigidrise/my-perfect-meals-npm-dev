        if (url.pathname === "/api/safety-pin/change") return reply({ success: true });
        if (url.pathname === "/api/safety-pin/remove") { hasPin = false; return reply({ success: true }); }
        if (url.pathname === "/api/safety-pin/set") { hasPin = true; return reply({ success: true }); }
