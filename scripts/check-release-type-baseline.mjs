#!/usr/bin/env node

import { createHash } from "node:crypto";
import {
  closeSync,
  existsSync,
  lstatSync,
  openSync,
  readFileSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { tmpdir } from "node:os";

const baselinePath = path.resolve("scripts/release-typecheck-baseline.json");
const tscPath = path.resolve(
  "node_modules",
  ".bin",
  process.platform === "win32" ? "tsc.cmd" : "tsc",
);

function fail(message, output = "") {
  console.error(`\nRelease typecheck failed: ${message}`);
  if (output) {
    console.error("\nTypeScript output:");
    console.error(output.trim().split("\n").slice(0, 80).join("\n"));
  }
  process.exit(1);
}

let baseline;
try {
  baseline = JSON.parse(readFileSync(baselinePath, "utf8"));
} catch (error) {
  fail(
    `could not read ${path.relative(process.cwd(), baselinePath)}. ` +
      "Restore the reviewed baseline before releasing.",
    error instanceof Error ? error.message : String(error),
  );
}

if (
  !Number.isInteger(baseline.diagnosticCount) ||
  typeof baseline.diagnosticsSha256 !== "string"
) {
  fail("the reviewed typecheck baseline is malformed.");
}

// buildVersion.ts is intentionally ignored and generated by update-version.js
// during builds, but it is imported by client code. Supply the same stable
// development module for every validation run, then restore the workspace
// exactly as it was. This keeps the compiler input deterministic without
// changing the product build artifact or requiring a generated file in Git.
const generatedBuildVersionPath = path.resolve("client/src/buildVersion.ts");
const releaseTypecheckLockPath = path.join(
  tmpdir(),
  `release-typecheck-${createHash("sha256")
    .update(process.cwd())
    .digest("hex")
    .slice(0, 16)}.lock`,
);
let releaseTypecheckLockHeld = false;
let releaseTypecheckLockFd;

try {
  releaseTypecheckLockFd = openSync(releaseTypecheckLockPath, "wx");
  releaseTypecheckLockHeld = true;
  closeSync(releaseTypecheckLockFd);
  releaseTypecheckLockFd = undefined;
} catch (error) {
  if (releaseTypecheckLockFd !== undefined) {
    try {
      closeSync(releaseTypecheckLockFd);
    } catch {
      // The original lock-acquisition error is more useful to the caller.
    }
  }
  if (releaseTypecheckLockHeld) {
    try {
      unlinkSync(releaseTypecheckLockPath);
    } catch {
      // Preserve the acquisition error; the lock is outside the workspace.
    }
    releaseTypecheckLockHeld = false;
  }
  if (error?.code === "EEXIST") {
    fail(
      "another release typecheck is already running for this workspace. " +
        "Wait for it to finish instead of running checks concurrently.",
    );
  }
  fail(
    "could not acquire the release typecheck lock.",
    error instanceof Error ? error.message : String(error),
  );
}

let previousGeneratedBuildVersion = null;
let originalGeneratedBuildVersionState = "unknown";
let result;
let operationError;
let restorationError;

try {
  if (existsSync(generatedBuildVersionPath)) {
    const generatedBuildVersionStat = lstatSync(generatedBuildVersionPath);
    if (!generatedBuildVersionStat.isFile()) {
      throw new Error(
        `${path.relative(process.cwd(), generatedBuildVersionPath)} is not a regular file`,
      );
    }
    previousGeneratedBuildVersion = readFileSync(generatedBuildVersionPath);
    originalGeneratedBuildVersionState = "present";
  } else {
    originalGeneratedBuildVersionState = "absent";
  }

  writeFileSync(
    generatedBuildVersionPath,
    'export const BUILD_VERSION = "dev";\n',
  );

  result = spawnSync(
    tscPath,
    ["--pretty", "false", "--incremental", "false", "--project", "tsconfig.json"],
    { encoding: "utf8" },
  );
} catch (error) {
  operationError = error;
} finally {
  try {
    if (originalGeneratedBuildVersionState === "unknown") {
      throw new Error(
        "the original buildVersion.ts state could not be determined; " +
          "leaving it untouched",
      );
    }
    if (originalGeneratedBuildVersionState === "absent") {
      if (existsSync(generatedBuildVersionPath)) {
        unlinkSync(generatedBuildVersionPath);
      }
      if (existsSync(generatedBuildVersionPath)) {
        throw new Error(
          `${path.relative(process.cwd(), generatedBuildVersionPath)} still exists after cleanup`,
        );
      }
    } else {
      writeFileSync(generatedBuildVersionPath, previousGeneratedBuildVersion);
      const restoredGeneratedBuildVersion = readFileSync(
        generatedBuildVersionPath,
      );
      if (!restoredGeneratedBuildVersion.equals(previousGeneratedBuildVersion)) {
        throw new Error(
          `${path.relative(process.cwd(), generatedBuildVersionPath)} was not restored byte-for-byte`,
        );
      }
    }
  } catch (error) {
    restorationError = error;
  }
}

try {
  if (releaseTypecheckLockHeld) {
    unlinkSync(releaseTypecheckLockPath);
    releaseTypecheckLockHeld = false;
  }
} catch (error) {
  restorationError ??= new Error(
    `could not release the temporary typecheck lock: ${
      error instanceof Error ? error.message : String(error)
    }`,
  );
}

if (restorationError) {
  fail(
    "could not safely restore the workspace after the root TypeScript check. " +
      "The release was stopped to avoid leaving generated files inconsistent.",
    restorationError instanceof Error
      ? restorationError.message
      : String(restorationError),
  );
}

if (operationError) {
  fail(
    "could not run the root TypeScript check.",
    operationError instanceof Error ? operationError.message : String(operationError),
  );
}

if (!result) {
  fail("the root TypeScript check returned no result.");
}

if (result.error) {
  fail("could not run the root TypeScript check.", result.error.message);
}

const output = `${result.stdout ?? ""}${result.stderr ?? ""}`;
const diagnostics = [
  ...output.matchAll(/^(.+?\(\d+,\d+\): error TS\d+: .+)$/gm),
].map((match) => match[1]).sort();

if (result.status !== 0 && diagnostics.length === 0) {
  fail(`TypeScript exited with status ${result.status}.`, output);
}

if (diagnostics.length === 0) {
  console.log("Root strict TypeScript check is clean.");
  process.exit(0);
}

const fingerprint = createHash("sha256")
  .update(diagnostics.join("\n"))
  .digest("hex");

if (
  diagnostics.length !== baseline.diagnosticCount ||
  fingerprint !== baseline.diagnosticsSha256
) {
  fail(
    `diagnostic set changed from the reviewed baseline ` +
      `(${baseline.diagnosticCount} / ${baseline.diagnosticsSha256}) to ` +
      `(${diagnostics.length} / ${fingerprint}). ` +
      "Resolve the new diagnostics, or deliberately refresh the baseline after " +
      "reviewing a focused debt-reduction change.",
    output,
  );
}

console.log(
  `Root strict TypeScript debt matches the reviewed baseline ` +
    `(${diagnostics.length} diagnostics).`,
);